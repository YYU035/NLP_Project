"""Record an actually completed review CSV; never generates human ratings."""
import argparse
from collections import Counter
import csv
from datetime import datetime
import hashlib
import json
from pathlib import Path


def validate(packet,review_csv):
    def read(path):
        with path.open(encoding='utf-8-sig',newline='') as handle:return list(csv.DictReader(handle))
    expected=read(packet/'human-review.csv');received=read(review_csv)
    by_id={row['sample_id']:row for row in received}
    if len(by_id)!=len(received) or set(by_id)!={r['sample_id'] for r in expected}:
        raise ValueError('Review must cover each sample exactly once')
    fields=['source_matches','relevant_to_claim','context_sufficient','within_input_limit']
    for original in expected:
        row=by_id[original['sample_id']]
        for name in ['claim','paper_id','page','start','end','passage_id','passage']:
            if row[name]!=original[name]:raise ValueError('Review source changed: '+name)
        if not row['reviewer'].strip() or not row['reviewed_at'].strip():raise ValueError('Reviewer identity and time are required')
        datetime.fromisoformat(row['reviewed_at'].replace('Z','+00:00'))
        for name in fields:
            if row[name] not in ('yes','no','uncertain'):raise ValueError('Missing human judgement: '+name)
    return {'status':'human_review_recorded','review_basis':'ratings supplied by named reviewer; not autogenerated',
        'samples':len(received),'reviewers':sorted({r['reviewer'] for r in received}),
        'ratings':{field:dict(Counter(r[field] for r in received)) for field in fields},
        'review_csv_sha256':hashlib.sha256(review_csv.read_bytes()).hexdigest(),
        'note':'Reviewed does not mean correct; negative/uncertain ratings are retained'}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--packet',type=Path,required=True);p.add_argument('--review-csv',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--record-in-packet',action='store_true')
    a=p.parse_args()
    if a.output.exists():p.error('Output exists')
    result=validate(a.packet,a.review_csv)
    with a.output.open('x') as h:json.dump(result,h,indent=2);h.write('\n')
    if a.record_in_packet:
        summary_path=a.packet/'summary.json'
        summary=json.loads(summary_path.read_text())
        summary['human_review_status']='recorded'
        summary['human_review_record']=result
        summary_path.write_text(json.dumps(summary,indent=2)+'\n')
    print(result['status'])
